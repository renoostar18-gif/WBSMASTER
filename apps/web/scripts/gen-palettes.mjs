// Writes src/themes/palettes.css from src/themes/palettes.json: one block per colour theme, in light and dark.
// Run `pnpm --filter @wbs-master/web gen:palettes` after editing the JSON; a unit test fails when the CSS is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = new URL('../src/themes/', import.meta.url);

/** The CSS for a list of palettes: [{ id, light: {...}, dark: {...} }]. */
export function renderPalettes(palettes) {
  const vars = c => [
    `--bg: ${c.bg}; --panel: ${c.panel}; --ink: ${c.ink}; --muted: ${c.muted}; --line: ${c.line}; --line2: ${c.line2};`,
    `--accent: ${c.accent}; --accent-ink: ${c.accentInk}; --sel: ${c.sel}; --n-bg: ${c.nBg};`,
    // level 1 is the accent; levels 2 to 6 are chosen to stay clearly apart from it and from each other
    `--l1: ${c.accent}; ${c.levels.map((x, i) => `--l${i + 2}: ${x};`).join(' ')}`,
  ].join('\n  ');
  const out = [
    '/* Colour themes. Generated by scripts/gen-palettes.mjs from palettes.json: do not edit by hand. */',
    '/* Each theme sets the same tokens as :root in styles.css, for light, for dark by system setting, and for dark by choice. */',
  ];
  for (const p of palettes) {
    const sel = `:root[data-palette="${p.id}"]`;
    out.push(`\n/* ${p.name.en} */`);
    out.push(`${sel} {\n  ${vars(p.light)}\n}`);
    out.push(`@media (prefers-color-scheme: dark) {\n  ${sel}:not([data-theme="light"]) {\n    ${vars(p.dark).replaceAll('\n  ', '\n    ')}\n  }\n}`);
    out.push(`${sel}[data-theme="dark"] {\n  ${vars(p.dark)}\n}`);
  }
  return `${out.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const palettes = JSON.parse(readFileSync(new URL('palettes.json', dir), 'utf8'));
  writeFileSync(new URL('palettes.css', dir), renderPalettes(palettes));
  console.log(`palettes.css: ${palettes.length} themes`);
}
